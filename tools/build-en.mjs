// Builds en/index.html (the English page, served at /en/) from index.html + js/data.js.
// Run after editing index.html or any STR string:   node tools/build-en.mjs
// No dependencies. Fails loudly if an expected piece of index.html is missing, so the
// English page can never silently ship half in Portuguese.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFileSync(root + p, 'utf8');

const sandbox = { window: {} };
vm.runInNewContext(read('js/data.js'), sandbox);
const EN = sandbox.window.IG_DATA.STR.en;

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

/* LF only: an editor saving CRLF on Windows must not break the exact-match swaps below */
let html = read('index.html').replace(/\r\n/g, '\n');

/* exact replacements: [from, to]; every one must match */
const swaps = [
  ['<!DOCTYPE html>\n<html lang="pt">', '<!DOCTYPE html>\n<!-- GENERATED by tools/build-en.mjs from index.html + js/data.js: do not edit, edit those and re-run. -->\n<html lang="en" data-root="../">'],
  ['<meta name="description" content="Software Engineer e Game Designer. Servidores de Minecraft, eventos ao vivo e software com IA que rodam com centenas de jogadores ao mesmo tempo.">',
   '<meta name="description" content="Software Engineer &amp; Game Designer. Minecraft servers, live events and AI-powered software that run with hundreds of players at the same time.">'],
  ['<link rel="canonical" href="https://icegames.me/">', '<link rel="canonical" href="https://icegames.me/en/">'],
  ['<meta property="og:url" content="https://icegames.me/">', '<meta property="og:url" content="https://icegames.me/en/">'],
  ['<meta property="og:description" content="Servidores de Minecraft, eventos ao vivo e software com IA que rodam com centenas de jogadores ao mesmo tempo.">',
   '<meta property="og:description" content="Minecraft servers, live events and AI-powered software that run with hundreds of players at the same time.">'],
  ['<meta property="og:locale" content="pt_BR">\n  <meta property="og:locale:alternate" content="en_US">',
   '<meta property="og:locale" content="en_US">\n  <meta property="og:locale:alternate" content="pt_BR">'],
  ['aria-label="Seções"', 'aria-label="Sections"'],
  ['aria-label="Foto de Vítor Albert; toque para virar"', 'aria-label="Photo of Vítor Albert; tap to flip"'],
  ['aria-label="Filtro"', 'aria-label="Filter"'],
  ['https://icegames.me/cv/pt', 'https://icegames.me/cv'],
];
for (const [from, to] of swaps) {
  if (!html.includes(from)) throw new Error('index.html no longer contains:\n  ' + from + '\nUpdate tools/build-en.mjs.');
  html = html.split(from).join(to);
}

/* the PT page's redirect-to-/en/ script */
const redirect = /  <script id="lang-redirect">[\s\S]*?<\/script>\n/;
if (!redirect.test(html)) throw new Error('index.html: <script id="lang-redirect"> not found');
html = html.replace(redirect, '');

/* text of every data-i18n element, and every data-i18n-placeholder */
const need = (key) => {
  if (EN[key] === undefined) throw new Error('STR.en is missing "' + key + '"');
  return esc(EN[key]);
};
html = html.replace(/(<([a-z0-9]+)\b[^>]*\sdata-i18n="([A-Za-z0-9]+)"[^>]*>)([^<]*)(<\/\2>)/g,
  (_, open, tag, key, text, close) => open + need(key) + close);
html = html.replace(/<[a-z]+\b[^>]*\sdata-i18n-placeholder="([A-Za-z0-9]+)"[^>]*>/g,
  (tag, key) => tag.replace(/placeholder="[^"]*"/, 'placeholder="' + need(key) + '"'));

/* the page lives one folder down */
html = html.replace(/\b(src|href)="(assets|css|js)\//g, '$1="../$2/');

const leftover = html.match(/data-i18n="[A-Za-z0-9]+">[^<]*(ção|ões|você|Sobre|Projetos)/);
if (leftover) throw new Error('Portuguese text left in the English page: ' + leftover[0]);

mkdirSync(root + 'en', { recursive: true });
writeFileSync(root + 'en/index.html', html);
console.log('en/index.html written');
